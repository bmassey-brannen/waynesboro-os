import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const ENV_PATHS = ['.env.local', '.env'];

function loadEnv() {
  for (const envPath of ENV_PATHS) {
    const fullPath = path.join(ROOT, envPath);
    if (!fs.existsSync(fullPath)) continue;
    const text = fs.readFileSync(fullPath, 'utf8');
    for (const line of text.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const match = trimmed.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
      if (!match) continue;
      const [, key, rawValue] = match;
      if (process.env[key]) continue;
      process.env[key] = rawValue.replace(/^["']|["']$/g, '');
    }
  }
}

loadEnv();

const snapshot = {
  sourceName: 'Mapbox Maps / Geocoding token',
  sourceUrl: 'https://docs.mapbox.com/',
  retrievedAt: new Date().toISOString(),
  credentialStatus: process.env.MAPBOX_ACCESS_TOKEN ? 'local_token_configured' : 'missing',
  publicUsePolicy: 'Credit-card-linked token. Use sparingly: no bulk geocoding, no repeated tile loops, no automated stress tests, and prefer cached/static map artifacts for public demo work.',
  intendedUse: [
    'Presentation-grade basemap polish after public data claims are already source-labeled',
    'Small number of manually approved geocodes for civic assets or project locations',
    'Static or cached map views when possible'
  ],
  guardrails: [
    'Do not publish the token into browser bundles unless it is intentionally scoped/restricted for public Mapbox client use.',
    'Do not run bulk address geocoding without explicit approval.',
    'Do not use Mapbox as the source of official parcel, zoning, or municipal boundary truth.',
    'Keep OSM/Census/official city map attribution and source labels visible when those are the underlying evidence.'
  ]
};

const outPath = path.join(ROOT, 'src/data/mapboxReadinessSeed.js');
const content = `// Generated by scripts/write-mapbox-readiness.js.\n// This file intentionally contains credential status/guardrails only, never the Mapbox token.\n\nexport const mapboxReadinessSeed = ${JSON.stringify(snapshot, null, 2)};\n`;
fs.writeFileSync(outPath, content);
console.log(`Mapbox readiness snapshot written: ${outPath}`);
console.log(`Credential status: ${snapshot.credentialStatus}`);
